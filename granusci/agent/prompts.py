# 分区假设运行时（--hypothesis-runtime，结构中介制）：ON 时的行为协议段
HR_PROMPT = """
# 假设运行时协议（结构中介制——系统强制，非自觉）

本 run 开启了分区假设运行时：假设循环四环的**触发**由系统强制执行，**环内决策**（裁决、机制解读、设计取舍）保留给你。四条硬规则：

1. **设计门**：dem_build_case / dem_modify_case 必须带 hypothesis_id（在档假设的 ID）或显式 exploratory=true。无引用的工况会被系统拒绝——不是惩罚，是把"这个工况为什么值得跑"变成可审计的结构。引用假设的工况会自动附上最近 DDDA 分区分析的边界加密建议（采纳与否是你的裁决权）。
2. **报数门**：每个工况跑完（系统观测到 done）且你完成测量提取后，必须用 hyp_report_measurement 报数（job_id + params 调控参数 + values 响应值 + evidence 出处）——有未报数的已完成工况时，新工况构建会被系统拒绝。纯结构观察/失败诊断等无数值产出的工况，报数时给 no_measurement_reason 参数显式销账。报数自动入账本，是后续一切结构分析的数据源。
3. **对账门**：报数后若涉及 registered/testing 假设，系统挂起对账账目——未对账时新工况构建与论文/报告提交均被拒绝。对账动作 = hypothesis_update（testing/supported/refuted，evidence 引用测量 id）。
4. **自动 DDDA**：报数矩阵积累到阈值后系统自动运行 DDDA 分区分析（分区结构/各区指数/边界），结果附在你的报数返回里。假设死亡（refuted）时系统自动把死亡位点记为 open_question——后继假设应针对失效机理重新表述。

工作节奏：设计工况（引用假设）→ 跑仿真 → 测量提取 → 报数 →（系统自动 DDDA+对账建议）→ hypothesis_update 裁决 → 下一批设计（参考分区边界建议）。探索性工况（exploratory=true）合法且不触发对账，但必须显式声明。
"""


def build_system_prompt(skills: dict, experience: str = "",
                        ablations: set[str] | None = None,
                        blind_kb: bool = False,
                        hr_enabled: bool = False) -> str:
    section = experience.strip() or "（暂无——首次运行或尚无沉淀）"
    text = SYSTEM_PROMPT_TEMPLATE.format(skill_catalog=catalog_text(skills),
                                         experience=section)
    if hr_enabled:
        text = text + HR_PROMPT
    if ablations and "no_mechanism" in ablations:
        text = text.replace(_RULE6_FULL, _RULE6_NO_MECHANISM)
    if blind_kb:
        # 盲 KB 消融：提示词不得提及博士论文（答案键存在性本身是泄漏）
        text = text.replace("先用 kb_search 查知识库（内含本方向博士论文全文与方法论）",
                            "先用 kb_search 查知识库（领域综述与方法论）")
    return text


